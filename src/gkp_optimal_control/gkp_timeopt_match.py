"""
Gate sequence  R(theta_k, alpha_k) -> CS_A(r_k) -> CS_B(t_k)   (k = 1..N)
optimized so that the oscillator state after layer k follows the
TIME-OPTIMAL evolution generated by H_opt (vacuum -> finite-energy GKP |0_L>).

Time-optimal evolution
----------------------
H_opt = i w (e^{-i phi}|chi><0| - h.c.)   acts as a rotation in span{|0>,|chi>},
|chi> = |T_perp>/||T_perp||,  |T_perp> = |T> - <0|T>|0>.

With the global phase chosen so that <0|T> = cos(theta0) >= 0:

    |T>      = cos(theta0)|0> + sin(theta0)|chi>
    |g(s)>   = cos(s theta0)|0> + sin(s theta0)|chi>,    s = t/t*  in [0,1]
    |<T|g(s)>|^2 = cos^2((1-s) theta0)

Loss (all oscillator states; qubit traced out)
    L = sum_k w_k [ 1 - sum_q |<g(k/N)|psi_k^q>|^2 ]  + small control regularizers
Matching the pure geodesic state at every layer forces the qubit to
disentangle at every layer and makes the whole Wigner trajectory follow
the H_opt one.

Target (paper Eq. 4):
    |mu_L; alpha,beta,Delta> ~ e^{-Delta^2 n} sum_{m=mu mod 2, l} e^{-i pi m l/2} |m alpha + l beta>

Pure NumPy / SciPy / Matplotlib (+ Pillow).  No JAX.
"""

