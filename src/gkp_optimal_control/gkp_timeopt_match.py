def track_loss_grad(p):
    P = p.reshape(NB, 4)
    psiF, states, cache = forward(P)

    loss = 0.0
    coef = np.zeros(NB + 1)
    for j in range(1, N + 1):
        k = j * K
        loss += wk[j] * (1.0 - fid_with(GEO[j], states[k]))
        coef[k] = -wk[j]                               # dL/dF at checkpoint

    loss += args.lambda_control * control_smoothness(P)
    loss += args.lambda_rot * np.sum(P[:, 2] ** 2)

    G = np.zeros((NB, 4))
    lam = np.zeros((2, D), dtype=complex)
    for k in reversed(range(NB)):
        if coef[k + 1] != 0.0:
            g = GEO[(k + 1) // K]
            st = states[k + 1]
            c0_, c1_ = np.vdot(g, st[0]), np.vdot(g, st[1])
            lam += coef[k + 1] * np.stack([g * c0_, g * c1_])
        lam = add_layer_gradient(k, lam, P, cache, G)

    G += args.lambda_control * control_smoothness_grad(P)
    G[:, 2] += args.lambda_rot * 2 * P[:, 2]
    return loss, G.ravel()


