def path_states(P, m):
    """every gate interpolated; s = fraction of the geodesic at that point"""
    P = P.reshape(NB, 4)
    psi = init_state()
    out = [("vacuum", 0, psi.copy(), 0.0)]
    for k, (r, t, theta, alpha) in enumerate(P):
        for g, name in enumerate(["qubit rotation", "CS_A squeezing", "CS_B squeezing"]):
            for f in np.linspace(0, 1, m + 1)[1:]:
                if g == 0:
                    st = rot(f * theta, alpha) @ psi
                elif g == 1:
                    st = np.stack([expA(f * r, psi[0]), expA(-f * r, psi[1])])
                else:
                    st = np.stack([expB(f * t, psi[0]), expB(-f * t, psi[1])])
                s = (k + (g + f) / 3) / NB
                out.append((name, k + 1, st, s))
            if g == 0:
                psi = rot(theta, alpha) @ psi
            elif g == 1:
                psi = np.stack([expA(r, psi[0]), expA(-r, psi[1])])
            else:
                psi = np.stack([expB(t, psi[0]), expB(-t, psi[1])])
    return out


