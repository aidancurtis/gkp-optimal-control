a = np.diag(np.sqrt(np.arange(1, D)), 1).astype(complex)
ad = a.conj().T
A = (a @ a - ad @ ad) / 2
B = 1j * (a @ a + ad @ ad) / 2
wA, VA = np.linalg.eigh(1j * A)
wB, VB = np.linalg.eigh(1j * B)
VAh, VBh = VA.conj().T, VB.conj().T


def expA(c, x):
    return VA @ (np.exp(-1j * c * wA) * (VAh @ x))


def expB(c, x):
    return VB @ (np.exp(-1j * c * wB) * (VBh @ x))


sx = np.array([[0, 1], [1, 0]], dtype=complex)
sy = np.array([[0, -1j], [1j, 0]], dtype=complex)
I2 = np.eye(2, dtype=complex)


def rot(theta, alpha):
    n = np.cos(alpha) * sx + np.sin(alpha) * sy
    return np.cos(theta / 2) * I2 - 1j * np.sin(theta / 2) * n


def hermite(x):
    H = np.zeros((D, len(x)))
    H[0] = np.pi ** (-0.25) * np.exp(-x**2 / 2)
    if D > 1:
        H[1] = np.sqrt(2) * x * H[0]
    for n in range(2, D):
        H[n] = np.sqrt(2 / n) * x * H[n - 1] - np.sqrt((n - 1) / n) * H[n - 2]
    return H


# ======================================================================
# TARGET: paper Eq. (4)
# ======================================================================
def build_target(Dfock, alpha, beta, Dl, mu, M):
    n = np.arange(Dfock)
    lognf = 0.5 * gammaln(n + 1)
    vec = np.zeros(Dfock, dtype=complex)
    for m in range(-M, M + 1):
        if (m - mu) % 2:
            continue
        for l in range(-M, M + 1):
            g = m * alpha + l * beta
            ph = np.exp(-1j * np.pi * m * l / 2)
            if abs(g) < 1e-14:
                vec[0] += ph
                continue
            # e^{-|g|^2/2} g^n / sqrt(n!)   (computed in logs for stability)
            logamp = -abs(g) ** 2 / 2 + n * np.log(abs(g)) - lognf
            vec += ph * np.exp(logamp + 1j * n * np.angle(g))
    vec *= np.exp(-Dl**2 * n)
    return vec


