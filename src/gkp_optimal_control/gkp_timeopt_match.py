# ======================================================================
# CIRCUIT
# ======================================================================
def init_state():
    psi = np.zeros((2, D), dtype=complex)
    psi[0, 0] = 1.0
    return psi


def apply_layer(psi, r, t, theta, alpha):
    p1 = rot(theta, alpha) @ psi
    p2 = np.stack([expA(r, p1[0]), expA(-r, p1[1])])
    return np.stack([expB(t, p2[0]), expB(-t, p2[1])])


def forward(P):
    P = P.reshape(NB, 4)
    psi = init_state()
    states, cache = [psi.copy()], []
    for r, t, theta, alpha in P:
        psi0 = psi
        R = rot(theta, alpha)
        psi1 = R @ psi0
        psi2 = np.stack([expA(r, psi1[0]), expA(-r, psi1[1])])
        psi3 = np.stack([expB(t, psi2[0]), expB(-t, psi2[1])])
        cache.append((psi0, psi2, psi3, R))
        psi = psi3
        states.append(psi.copy())
    return psi, states, cache


def fid_with(g, psi):
    """oscillator fidelity with pure state g, qubit traced out"""
    return abs(np.vdot(g, psi[0])) ** 2 + abs(np.vdot(g, psi[1])) ** 2


def purity_of(psi):
    rq = psi @ psi.conj().T
    return float(np.real(np.trace(rq @ rq)))


# ======================================================================
# REGULARIZERS
# ======================================================================
def control_smoothness(P):
    if NB <= 1:
        return 0.0
    d = P[1:] - P[:-1]
    d[:, 3] = (d[:, 3] + np.pi) % (2 * np.pi) - np.pi
    return np.sum(d**2)


def control_smoothness_grad(P):
    G = np.zeros_like(P)
    d = P[1:] - P[:-1]
    d[:, 3] = (d[:, 3] + np.pi) % (2 * np.pi) - np.pi
    G[:-1] -= 2 * d
    G[1:] += 2 * d
    return G


# ======================================================================
# ADJOINT (per layer)
# ======================================================================
def add_layer_gradient(k, lam, P, cache, G):
    r, t, theta, alpha = P[k]
    psi0, psi2, psi3, R = cache[k]

    G[k, 1] += 2 * np.real(np.vdot(lam[0], B @ psi3[0]) - np.vdot(lam[1], B @ psi3[1]))
    lam = np.stack([expB(-t, lam[0]), expB(t, lam[1])])

    G[k, 0] += 2 * np.real(np.vdot(lam[0], A @ psi2[0]) - np.vdot(lam[1], A @ psi2[1]))
    lam = np.stack([expA(-r, lam[0]), expA(r, lam[1])])

    ns = np.cos(alpha) * sx + np.sin(alpha) * sy
    dR_dtheta = -0.5j * ns @ R
    dR_dalpha = -1j * np.sin(theta / 2) * (-np.sin(alpha) * sx + np.cos(alpha) * sy)
    G[k, 2] += 2 * np.real(np.sum(np.conj(lam) * (dR_dtheta @ psi0)))
    G[k, 3] += 2 * np.real(np.sum(np.conj(lam) * (dR_dalpha @ psi0)))
    return R.conj().T @ lam


# ======================================================================
# OBJECTIVE: track the geodesic state at every layer
# ======================================================================
