# ======================================================================
# GREEDY INITIALIZATION: layer k maximizes overlap with g(k/N)
# ======================================================================
def greedy_init(rng):
    psi = init_state()
    P = np.zeros((NB, 4))
    prev = np.zeros(4)
    for k in range(1, NB + 1):
        g = geo_state(k / NB)
        best = None
        for trial in range(4):
            x0 = prev.copy() if trial == 0 else prev + rng.normal(0, 0.1, 4)
            res = minimize(lambda x: 1 - fid_with(g, apply_layer(psi, *x)),
                           x0, method="BFGS", options={"maxiter": 60})
            if best is None or res.fun < best.fun:
                best = res
        P[k - 1] = best.x
        prev = best.x
        psi = apply_layer(psi, *best.x)
    return P.ravel()


